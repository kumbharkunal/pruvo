import type { NextConfig } from "next";

// "demo" (default) keeps the site out of search engines until Pruvo signs off.
const isDemo = (process.env.NEXT_PUBLIC_SITE_ENV ?? "demo") === "demo";
const isProd = process.env.NODE_ENV === "production";

// Static generation rules out per-request nonces, so inline scripts are allowed; nothing third-party loads.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "form-action 'self' https://docs.google.com",
  "base-uri 'self'",
  "object-src 'none'",
].join("; ");

const security = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
  ...(isProd ? [{ key: "Content-Security-Policy", value: csp }] : []),
  ...(isDemo ? [{ key: "X-Robots-Tag", value: "noindex, nofollow" }] : []),
];

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  images: {
    // Every photo is pre-generated by scripts/images.mjs at these widths and served as static files
    // through a custom loader (src/lib/images.ts); keep in step with scripts/image-slots.mjs.
    deviceSizes: [480, 640, 828, 1080, 1280, 1672, 1920],
    imageSizes: [160, 240, 320],
  },
  async headers() {
    return [
      { source: "/:path*", headers: security },
      {
        // File names carry a content hash, so they never change in place.
        source: "/images/:path*",
        headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }],
      },
      {
        source: "/brand/:path*",
        headers: [{ key: "Cache-Control", value: "public, max-age=86400, stale-while-revalidate=604800" }],
      },
    ];
  },
};

export default nextConfig;
